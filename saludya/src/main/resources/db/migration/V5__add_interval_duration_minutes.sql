CREATE TABLE IF NOT EXISTS hospital_configurations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    max_capacity_per_slot INTEGER NOT NULL,
    booking_order_scope VARCHAR(20) NOT NULL,
    check_in_tolerance_minutes INTEGER NOT NULL,
    post_call_tolerance_minutes INTEGER NOT NULL,
    reassignment_response_timeout_min INTEGER NOT NULL,
    booking_cutoff_time TIME NOT NULL,
    cancellation_deadline_hours INTEGER NOT NULL,
    attendance_queue_visible BOOLEAN NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

