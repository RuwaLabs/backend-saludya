CREATE TABLE staff_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user BIGINT NOT NULL UNIQUE REFERENCES users(id),
    dni VARCHAR(8) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    lastname VARCHAR(100) NOT NULL,
    birth_date DATE NOT NULL,
    phone VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE user_sessions (
    id VARCHAR(36) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_user_sessions_user ON user_sessions(user_id);
CREATE TABLE password_reset_tokens (
    id VARCHAR(36) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_password_reset_tokens_user ON password_reset_tokens(user_id);
CREATE TABLE iam_notification_outboxes (
    id VARCHAR(36) PRIMARY KEY,
    recipient VARCHAR(150) NOT NULL,
    subject VARCHAR(150) NOT NULL,
    encrypted_body TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_outbox_status CHECK(status IN ('PENDING','SENT','FAILED'))
);
CREATE INDEX idx_outbox_due ON iam_notification_outboxes(status,next_attempt_at);
CREATE TABLE account_recovery_requests (
    id VARCHAR(36) PRIMARY KEY,
    dni VARCHAR(8) NOT NULL,
    contact_email VARCHAR(150) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    resolved_by BIGINT REFERENCES users(id),
    resolved_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_recovery_status CHECK(status IN ('OPEN','RESOLVED'))
);
CREATE INDEX idx_recovery_status ON account_recovery_requests(status,created_at);
